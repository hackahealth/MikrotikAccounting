"""آموزش خودکار ورود اول: بخش‌های برنامه را به هر کاربر پنل (فقط بخش‌هایی که به آن‌ها دسترسی دارد) و صفحه
«مصرف اینترنت من» را به کاربران اینترنت معرفی می‌کند. یک بار خودکار نشان داده می‌شود و از منو دوباره قابل دیدن است."""

VERSION = "1"       # change to show the tour again to everyone after big changes


def _step(key, title, text):
    return {"el": f'[data-tour="{key}"]' if key else "", "title": title, "text": text}


def panel_steps(me, perms, scope_label="", roles=None):
    """Steps for the panel sidebar. The browser skips steps whose menu item is not on the page."""
    from .auth import ROLES, is_local
    role = (roles or ROLES).get(me.role, ("", []))[0]
    scoped = bool(scope_label)
    intro = f"این راهنمای کوتاه بخش‌هایی از برنامه را که شما به آن‌ها دسترسی دارید معرفی می‌کند. نقش شما: «{role}»."
    if scoped:
        intro += " شما فقط کارکنان محدوده خودتان را می‌بینید و دسترسی‌تان فقط مشاهده است."
    steps = [_step("", f"خوش آمدید {me.full_name or me.username}", intro + " با «بعدی» جلو بروید."),
             {"el": ".scope-bar", "title": "محدوده دسترسی شما",
              "text": f"این نوار همیشه بالای صفحه است: {scope_label}. همه گزارش‌ها، فهرست‌ها و خروجی‌ها فقط همین "
                      "محدوده را نشان می‌دهند."} if scoped else None,
             _step("dashboard", "داشبورد", "نمای امروز در یک نگاه: کاربران آنلاین، حجم مصرف امروز (اینترنت و داخل "
                   "شبکه)، مصرف ساعتی، نوع استفاده (ویدیو، شبکه اجتماعی، دانلود و ...) و پرمصرف‌ترین کاربران."),
             _step("mgmt", "گزارش مدیریتی", "خلاصه مصرف هر دفتر، واحد و گروه در بازه دلخواه، مقایسه با دوره قبل، "
                   "نمودارها، خروجی Excel و نسخه چاپی برای جلسه."),
             _step("attendance", "ساعات اتصال کارکنان", "اولین ورود و آخرین خروج هر کارمند در هر روز و مجموع ساعات "
                   "اتصال؛ مناسب واحد منابع انسانی، با خروجی Excel."),
             _step("calls", "تماس‌ها", "آمار تماس‌های تلفنی از سرورهای ایزابل: ورودی، خروجی، مدت مکالمه، ساعات "
                   "پرتماس، مقاصد پرتماس و تماس‌های بی‌پاسخی که کسی برنگشته، برای هر نفر، دفتر و واحد."),
             _step("reports", "گزارش‌های مصرف", "مصرف هر کاربر، گروه، دفتر یا واحد در هر بازه زمانی: حجم، سایت‌ها، "
                   "نوع استفاده، اتصال‌ها و سرعت. روی نام هر کاربر بزنید تا گزارش خودش باز شود."
                   + (" خروجی Excel هم دارد." if "reports_export" in perms else "")),
             _step("traffic", "ترافیک روترها", "گراف سرعت لحظه‌ای و حجم مصرف هر روتر، جدا برای اینترنت و شبکه "
                   "داخلی؛ خط امروز پررنگ روی خط کمرنگ دیروز می‌افتد تا مقایسه در یک نگاه باشد."),
             _step("live", "کاربران آنلاین", "همه اتصال‌های فعال هات‌اسپات و VPN با IP، دستگاه، روتر، سرعت لحظه‌ای و "
                   "حجم؛ خودکار به‌روز می‌شود."
                   + (" از همین‌جا می‌توانید اتصال یک کاربر را قطع کنید." if "live_disconnect" in perms else "")),
             _step("users", "کارکنان" if scoped else "کاربران",
                   "فهرست کارکنان محدوده شما با وضعیت و مصرف هر کدام." if scoped else
                   "کاربران اینترنت (محلی، Active Directory و اکانت‌های روتر) با جستجو و فیلتر."
                   + (" ساخت و ویرایش کاربر، سرعت، سهمیه حجم، ساعات مجاز، تاریخ انقضا و ویرایش گروهی (که روی AD هم "
                      "ثبت می‌شود) همین‌جاست." if "users_edit" in perms else "")),
             _step("groups", "گروه‌ها", "سیاست مشترک کاربران: سرعت، سهمیه حجم و دوره آن، ساعات مجاز و تعداد اتصال "
                   "همزمان. هر گروه می‌تواند به یک گروه AD وصل باشد."),
             _step("devices", "دستگاه‌ها", "هر دستگاه (MAC) با نوع، سازنده، IPها و کاربرانی که رویش وارد شده‌اند، با "
                   "بازه زمانی دقیق. با جستجوی یک IP و یک زمان معلوم می‌شود چه کسی پشت آن بوده است."),
             _step("logs", "لاگ ورود", "همه تلاش‌های ورود به اینترنت، موفق و ناموفق، با علت رد شدن (رمز اشتباه، خارج از "
                   "ساعت مجاز، حجم تمام‌شده و ...)."),
             _step("org", "دفترها و واحدها", "تعریف دفترها و واحدها و تخصیص کاربران به آن‌ها؛ پایه گزارش مدیریتی و "
                   "محدوده مدیران دفتر/واحد."),
             _step("mt_local", "اکانت‌های محلی میکروتیک", "کاربران هات‌اسپات و VPN که مستقیم روی خود روتر تعریف "
                   "شده‌اند: ساخت، ویرایش، کارت ووچر گروهی، صفر کردن مصرف و قطع اتصال."),
             _step("pbx", "سرورهای ایزابل", "اتصال به یک یا چند سرور ایزابل (فقط‌خواندنی)، بازه داخلی‌ها و ترانک‌ها، و "
                   "داخلی‌هایی که هنوز به کسی تخصیص داده نشده‌اند."),
             _step("hotspot", "فولدر hotspot روترها", "صفحه ورود هات‌اسپات را ویرایش یا بارگذاری کنید و یک‌جا روی "
                   "روترها بفرستید؛ قبل از هر تغییر از نسخه روتر پشتیبان گرفته می‌شود."),
             _step("nas", "روترها", "تعریف روترهای میکروتیک (RADIUS، API، Traffic-Flow)، روترهای دفاتر پشت NAT، تفکیک "
                   "داخل شبکه و اینترنت، و بخش عیب‌یابی که نشان می‌دهد از هر روتر چه چیزی می‌رسد."),
             _step("ad", "Active Directory", "اتصال به AD، همگام‌سازی کاربران با دفتر و واحد و موبایل، و نگاشت گروه‌های "
                   "AD به گروه‌های اینترنت."),
             _step("admins", "کاربران پنل", "چه کسی به این پنل دسترسی دارد و چه کاری می‌تواند بکند: نقش‌ها، دسترسی "
                   "سفارشی، محدوده دفتر/واحد، و حساب‌های AD (مثلاً مدیر دفتر با رمز دامنه خودش)."),
             _step("audit", "لاگ فعالیت پنل", "هر کاری که کاربران پنل انجام داده‌اند (ورود، تغییر کاربر، قطع اتصال و "
                   "...) با زمان و IP."),
             _step("account", "حساب شما", "دسترسی‌های خودتان را اینجا می‌بینید. "
                   + ("رمز پنل را هم همین‌جا عوض کنید." if is_local(me) else
                      "رمز شما همان رمز دامنه (ویندوز) است.")),
             _step("my", "مصرف اینترنت من", "مصرف اینترنت و اتصال‌های خودتان، بدون ورود دوباره."),
             _step("help", "راهنمای برنامه", "هر وقت خواستید این آموزش را از همین‌جا دوباره ببینید. در هر صفحه هم "
                   "توضیح‌های کوچک خاکستری زیر هر بخش، کار آن را می‌گویند.")]
    return [s for s in steps if s]


def my_steps(user):
    """Steps for the internet user's own usage page (/my)."""
    ad = user.source == "ldap"
    return [
        _step("", f"سلام {user.full_name or user.username}", "در این صفحه مصرف اینترنت و وضعیت حسابتان را می‌بینید و "
              "رمزتان را عوض می‌کنید. با «بعدی» بخش‌ها را ببینید."),
        _step("status", "وضعیت حساب", "فعال، غیرفعال، منقضی، حجم تمام‌شده یا خارج از ساعات مجاز؛ و این‌که الان آنلاین "
              "هستید یا نه."),
        _step("quota", "حجم باقی‌مانده", "سهمیه دوره شما (روزانه، هفتگی یا ماهانه) و مقداری که مصرف شده. وقتی تمام شود "
              "اتصال تا دوره بعد قطع می‌شود."),
        _step("today", "مصرف امروز و این ماه", "«اینترنت» مصرف واقعی اینترنت است و «داخل شبکه» دسترسی به سرورها و "
              "منابع داخلی سازمان."),
        _step("daily", "مصرف روزانه", "نمودار و جدول مصرف هر روز در ۳۰ روز اخیر."),
        _step("info", "مشخصات حساب", "گروه، سرعت، ساعات مجاز و تاریخ انقضای حساب، و نوع استفاده شما (ویدیو، شبکه "
              "اجتماعی، دانلود و ...)."),
        _step("sessions", "اتصال‌های اخیر", "هر ورود با زمان، مدت، دستگاه، IP و حجم. اگر ورودی را نمی‌شناسید رمزتان را "
              "عوض کنید."),
        _step("password", "تغییر رمز", "رمز دامنه (ویندوز) شما همین‌جا هم عوض می‌شود." if ad else
              "رمز جدید برای اتصال به هات‌اسپات و VPN استفاده می‌شود."),
        _step("help", "راهنما", "هر وقت خواستید این آموزش را از اینجا دوباره ببینید."),
    ]
